# 缺陷状态流转
[新建] → [确认] → [修复] → [验证] → [关闭]
  │        │        │        │        │
  │        │        │        │        └── 测试验证通过
  │        │        │        └── 开发修复完成
  │        │        └── 开发开始修复
  │        └── 缺陷确认有效
  └── 缺陷提交

# 缺陷优先级定义
P0 - 阻断级：核心业务流程无法运行，无法进行测试
P1 - 严重级：核心功能失效，有 workaround 但影响效率
P2 - 一般级：非核心功能失效，不影响主要业务流程
P3 - 轻微级：UI问题、文本错误等轻微问题